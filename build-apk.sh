#!/bin/sh
set -eu

BASE_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)

PKG_VERSION=$(grep '^PKG_VERSION:=' "$BASE_DIR/Makefile" | cut -d= -f2 | tr -d '\r')
PKG_RELEASE=$(grep '^PKG_RELEASE:=' "$BASE_DIR/Makefile" | cut -d= -f2 | tr -d '\r')
APK_VER="${PKG_VERSION}-r${PKG_RELEASE}"

OUTPUT=${1:-"$BASE_DIR/releases/luci-theme-streamline_${APK_VER}_all.apk"}
BUILD_DIR=$(mktemp -d "${TMPDIR:-/tmp}/streamline-apk.XXXXXX")
trap 'rm -rf "$BUILD_DIR"' EXIT HUP INT TERM

CONTROL_DIR="$BUILD_DIR/control"
DATA_DIR="$BUILD_DIR/data"
mkdir -p "$CONTROL_DIR" \
	"$DATA_DIR/www" \
	"$DATA_DIR/usr/lib/lua/luci" \
	"$DATA_DIR/usr/share/ucode/luci" \
	"$DATA_DIR/etc/uci-defaults"

# 1. Populate data payload
cp -R "$BASE_DIR/htdocs/." "$DATA_DIR/www/"
cp -R "$BASE_DIR/luasrc/." "$DATA_DIR/usr/lib/lua/luci/"
cp -R "$BASE_DIR/ucode/." "$DATA_DIR/usr/share/ucode/luci/"
cp -R "$BASE_DIR/root/." "$DATA_DIR/"
chmod 0755 "$DATA_DIR/etc/uci-defaults/30_luci-theme-streamline"

# Guarantee pure Unix LF line endings across all text files
find "$DATA_DIR" -type f \( -name "*.htm" -o -name "*.ut" -o -name "*.js" -o -name "*.css" -o -name "*.json" -o -name "*.svg" -o -name "*.sh" -o -name "30_luci-theme-streamline" \) -exec sed -i 's/\r$//' {} +

# 2. Build data.tar.gz
tar --format=gnu --sort=name --owner=0 --group=0 --numeric-owner --mtime='@0' \
	-C "$DATA_DIR" -czf "$BUILD_DIR/data.tar.gz" .

# 3. Calculate metrics for .PKGINFO
SIZE=$(du -sb "$DATA_DIR" 2>/dev/null | cut -f1 || du -sk "$DATA_DIR" | awk '{print $1 * 1024}')
DATAHASH=$(sha256sum "$BUILD_DIR/data.tar.gz" | awk '{print $1}')
BUILDDATE=$(date +%s)
COMMIT=$(git -C "$BASE_DIR" rev-parse HEAD 2>/dev/null || echo "unknown")

# 4. Populate control payload
cat <<EOF > "$CONTROL_DIR/.PKGINFO"
# Generated by Streamline build-apk.sh
pkgname = luci-theme-streamline
pkgver = ${APK_VER}
pkgdesc = Modern, clean, and high-performance LuCI theme for OpenWrt
url = https://github.com/RPSouto/streamline-openwrt-theme
builddate = ${BUILDDATE}
packager = Streamline contributors
size = ${SIZE}
arch = all
origin = luci-theme-streamline
commit = ${COMMIT}
license = Apache-2.0
depend = libc luci-base
datahash = ${DATAHASH}
EOF

cp "$BASE_DIR/packaging/postinst" "$CONTROL_DIR/.post-install"
cp "$BASE_DIR/packaging/postrm" "$CONTROL_DIR/.post-deinstall"
chmod 0755 "$CONTROL_DIR/.post-install" "$CONTROL_DIR/.post-deinstall"
find "$CONTROL_DIR" -type f -exec sed -i 's/\r$//' {} +

# 5. Build control.tar.gz
tar --format=gnu --sort=name --owner=0 --group=0 --numeric-owner --mtime='@0' \
	-C "$CONTROL_DIR" -czf "$BUILD_DIR/control.tar.gz" .

# 6. Concatenate streams to form APK package
mkdir -p "$(dirname -- "$OUTPUT")"
rm -f "$OUTPUT"
cat "$BUILD_DIR/control.tar.gz" "$BUILD_DIR/data.tar.gz" > "$OUTPUT"

# 7. Verification
if command -v node >/dev/null 2>&1 && [ -f "$BASE_DIR/tools/verify-apk.js" ]; then
	node "$BASE_DIR/tools/verify-apk.js" "$OUTPUT"
fi

OUTPUT_REAL=$(CDPATH= cd -- "$(dirname -- "$OUTPUT")" && pwd)/$(basename -- "$OUTPUT")
RELEASES_REAL=$(CDPATH= cd -- "$BASE_DIR/releases" 2>/dev/null && pwd || true)
if [ -n "$RELEASES_REAL" ] && [ "$OUTPUT_REAL" != "$RELEASES_REAL/$(basename -- "$OUTPUT")" ]; then
	cp -f "$OUTPUT" "$BASE_DIR/releases/"
fi

echo "Criado: $OUTPUT"
